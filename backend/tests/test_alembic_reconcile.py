"""Revision 0002 brings a production-shaped database to exactly the 0001 schema (refactor 3.8b).

Production was built by ``init_db``, so it differs from the baseline in a known
set of ways (refactor-review/alembic-prod-compare-2026-11-07.md). These tests
build a database with 0001, hand-apply that drift, run ``alembic upgrade head``
and compare the result with a database that never drifted. Runs on SQLite by
default and on Postgres under TEST_DATABASE_URL.
"""

from __future__ import annotations

from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from alembic.migration import MigrationContext
from alembic.operations import Operations
from sqlalchemy import Engine, text

from tests.db_support import make_bare_engine
from tests.test_alembic_baseline import _alembic_config, _describe

# (table, column, production server default as the _ensure_* helpers spelled it)
_NULLABLE_IN_PRODUCTION = [
    ("analyst_access", "auto_approved", "BOOL0"),
    ("analyst_access", "topup_usd", "0"),
    ("analyst_usage", "duration_ms", "0"),
    ("analyst_usage", "outcome", "'ok'"),
    ("analyst_usage", "tool_calls", "0"),
    ("decks", "is_main", "BOOL0"),
    ("duel_match_progress", "closed", "BOOL0"),
    ("feedback", "discord_author", "''"),
    ("group_buys", "external_order_id", "''"),
    ("group_buys", "is_public", "BOOL0"),
    ("group_buys", "order_notes", "''"),
    ("group_buys", "receipt_text", "''"),
    ("group_buys", "shipping_cost", "0"),
    ("group_buys", "shipping_split", "'equal'"),
    ("group_buys", "tax_cost", "0"),
    ("users", "session_version", "'0'"),
    ("users", "sum_across_leaders", "BOOL0"),
]

_OUTBOX_DDL = """CREATE TABLE duel_match_outbox (
    match_id VARCHAR(64) PRIMARY KEY, payload TEXT NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0, available_at TIMESTAMP, delivered_at TIMESTAMP
)"""


def _upgrade(engine: Engine, revision: str) -> None:
    cfg = _alembic_config()
    with engine.begin() as conn:
        cfg.attributes["connection"] = conn
        command.upgrade(cfg, revision)


def _apply_production_drift(engine: Engine) -> None:
    """Make an 0001 database look like production (the differences in the compare report)."""
    false = "false" if engine.dialect.name == "postgresql" else "0"
    with engine.begin() as conn:
        ops = Operations(MigrationContext.configure(conn))
        for table, column, default in _NULLABLE_IN_PRODUCTION:
            default = false if default == "BOOL0" else default
            with ops.batch_alter_table(table) as batch:
                batch.alter_column(column, nullable=True, server_default=text(default))
        with ops.batch_alter_table("user_sharing") as batch:
            batch.alter_column("collection", server_default="off")
        conn.execute(text("DROP INDEX ix_analyst_eval_runs_suite"))
        conn.execute(text("DROP INDEX ix_analyst_usage_thread_id"))
        conn.execute(text(_OUTBOX_DDL))
        conn.execute(text("CREATE INDEX duel_match_outbox_due ON duel_match_outbox (available_at)"))


def _fresh_head_schema() -> dict[str, dict]:
    engine = make_bare_engine()
    _upgrade(engine, "head")
    schema = _describe(engine)
    engine.dispose()
    return schema


def test_0002_reconciles_a_production_shaped_database_to_the_0001_schema_refactor_3_8b() -> None:
    engine = make_bare_engine()
    _upgrade(engine, "0001")
    _apply_production_drift(engine)
    drifted = _describe(engine)
    # The drift really is there, so equality below proves 0002 undid it.
    assert drifted["decks"]["columns"]["is_main"][1] is True
    assert drifted["user_sharing"]["columns"]["collection"][2] != "'friends'"
    assert not any(ix[0] == "ix_analyst_usage_thread_id" for ix in drifted["analyst_usage"]["indexes"])

    _upgrade(engine, "head")
    reconciled = _describe(engine)
    engine.dispose()

    expected = _fresh_head_schema()
    # duel_match_outbox is game-server owned: 0002 leaves it alone.
    outbox = reconciled.pop("duel_match_outbox")
    assert "match_id" in outbox["columns"]
    assert sorted(reconciled) == sorted(expected)
    for table, want in expected.items():
        assert reconciled[table] == want, f"schema differs for table {table!r}"


def test_0002_backfills_null_rows_before_setting_not_null_refactor_3_8b() -> None:
    engine = make_bare_engine()
    _upgrade(engine, "0001")
    _apply_production_drift(engine)
    with engine.begin() as conn:
        conn.execute(
            text(
                "INSERT INTO feedback (kind, message, app, page, client_build, viewport, user_agent, room_id, "
                "discord_author, status) VALUES ('bug', 'm', 'planner', '', '', '', '', '', NULL, 'open')"
            )
        )
    _upgrade(engine, "head")
    with engine.connect() as conn:
        assert conn.execute(text("SELECT discord_author FROM feedback")).scalar_one() == ""
    engine.dispose()


def test_env_include_object_hides_the_game_server_outbox_from_autogenerate_refactor_3_8b() -> None:
    engine = make_bare_engine()
    _upgrade(engine, "head")
    with engine.begin() as conn:
        conn.execute(text(_OUTBOX_DDL))
        conn.execute(text("CREATE INDEX duel_match_outbox_due ON duel_match_outbox (available_at)"))
    cfg = _alembic_config()
    with engine.connect() as conn:
        cfg.attributes["connection"] = conn
        # Other model-vs-0001 differences may exist (duel_events server defaults); only the outbox matters here.
        try:
            command.check(cfg)
        except AutogenerateDiffsDetected as exc:
            detail = str(exc)
        else:
            detail = ""
    engine.dispose()
    assert "duel_match_outbox" not in detail
